import { chromium } from 'playwright-core';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 3840, height: 2160 } });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto('http://localhost:5173/?t=08:10');
await page.waitForFunction(() => window.__ats?.store?.snap, null, { timeout: 180000 });
await page.waitForTimeout(2000);
await page.evaluate(async () => {
  const s = window.__ats.store; const topo = s.topo;
  await s.command({ c: 'fault', kind: 'zcFail', target: 3, duration: 1800 });
  const sec = topo.sections.find((x) => x.track === 'DN' && x.kind === 'plain' && x.chainFrom > 12000 && x.chainTo < 14000);
  await s.command({ c: 'fault', kind: 'axle', target: sec.id, duration: 600 });
  const sw = topo.switches.find((x) => x.kind === 'crossover' && x.station === 16);
  await s.command({ c: 'fault', kind: 'switch', target: sw.id, duration: 600 });
  const tr = s.snap.trains.find((t) => t.inService && t.chain > 27000 && t.chain < 31000 && t.v > 5);
  if (tr) await s.command({ c: 'fault', kind: 'trainFail', target: tr.id, duration: 0, recoverable: false });
  const tsr = topo.sections.filter((x) => x.track === 'UP' && x.chainFrom > 18900 && x.chainTo < 20300).map((x) => x.id);
  await s.command({ c: 'setTsr', sections: tsr, kmh: 25 });
  await s.command({ c: 'platformHold', platform: topo.stations[12].platforms.DN, on: true });
});
await page.waitForTimeout(25000);
await page.evaluate(async () => { const s = window.__ats.store; await s.command({ c: 'zoneLevel', zones: [3], level: 'TBTC' }); s.select({ kind: 'zone', id: 3 }); });
await page.waitForTimeout(12000);
await page.screenshot({ path: out });
console.log(errs.join('\n') || 'no errors');
await browser.close();
